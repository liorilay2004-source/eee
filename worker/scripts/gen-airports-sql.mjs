#!/usr/bin/env node
/**
 * Builds migrations/0002_seed_airports.sql from src/airports/cities.json (SPEC 4.3, 12).
 *
 *   node scripts/gen-airports-sql.mjs           write the migration
 *   node scripts/gen-airports-sql.mjs --check   exit 1 when the committed migration is out of date
 *
 * Output is a pure function of cities.json: no timestamps, rows sorted by IATA code, LF line endings.
 * One row per commercial airport. The city name and popularity are repeated on each of a city's airports
 * (the airports table is flat, see 0001_init.sql). Lat/lon stay NULL: the dataset carries no coordinates.
 *
 * D1 splits migration files into statements on semicolons, so a semicolon may only appear as a statement
 * terminator: it is rejected inside every string value and never used in comments.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src", "airports", "cities.json");
const OUT = join(ROOT, "migrations", "0002_seed_airports.sql");

/**
 * A city's first listed airport is its main one and keeps the city's popularity. Secondary airports rank a
 * little lower, so autocomplete and "popular destinations" lists put LHR ahead of LTN instead of leaving a tie.
 */
const SECONDARY_PENALTY = 5;

const IATA = /^[A-Z]{3}$/;
const ISO2 = /^[A-Z]{2}$/;

function fail(msg) {
  throw new Error(`cities.json: ${msg}`);
}

/** SQL string literal. Single quotes are doubled, and characters that would break statement splitting are rejected. */
function lit(value, what) {
  if (typeof value !== "string") fail(`${what} must be a string`);
  if (/[;\0\r\n\\]/.test(value)) fail(`${what} contains a character that is not allowed in the seed: ${JSON.stringify(value)}`);
  return `'${value.replaceAll("'", "''")}'`;
}

function buildRows(cities) {
  if (!Array.isArray(cities) || cities.length === 0) fail("expected a non-empty array");
  const rows = new Map(); // iata -> row
  const cityCodes = new Set();
  for (const c of cities) {
    const id = c?.cityIata;
    if (typeof id !== "string" || !IATA.test(id)) fail(`bad cityIata ${JSON.stringify(id)}`);
    if (cityCodes.has(id)) fail(`duplicate cityIata ${id}`);
    cityCodes.add(id);
    if (typeof c.cityEn !== "string" || c.cityEn.trim() === "") fail(`${id}: empty cityEn`);
    if (typeof c.cityHe !== "string") fail(`${id}: cityHe must be a string`);
    if (typeof c.countryCode !== "string" || !ISO2.test(c.countryCode)) fail(`${id}: bad countryCode ${JSON.stringify(c.countryCode)}`);
    if (!Number.isInteger(c.popularity) || c.popularity < 1 || c.popularity > 100) fail(`${id}: popularity must be an integer 1-100`);
    if (!Array.isArray(c.airports) || c.airports.length === 0) fail(`${id}: no airports`);
    c.airports.forEach((a, i) => {
      if (typeof a?.iata !== "string" || !IATA.test(a.iata)) fail(`${id}: bad airport iata ${JSON.stringify(a?.iata)}`);
      if (rows.has(a.iata)) fail(`airport ${a.iata} listed twice`);
      if (typeof a.nameEn !== "string" || a.nameEn.trim() === "") fail(`${a.iata}: empty nameEn`);
      const popularity = i === 0 ? c.popularity : Math.max(1, c.popularity - SECONDARY_PENALTY);
      rows.set(
        a.iata,
        `INSERT OR REPLACE INTO airports(iata, city_iata, name_en, city_en, city_he, country_code, lat, lon, popularity) VALUES (` +
          [
            lit(a.iata, "iata"),
            lit(id, "city_iata"),
            lit(a.nameEn, `${a.iata} name_en`),
            lit(c.cityEn, `${id} city_en`),
            c.cityHe === "" ? "NULL" : lit(c.cityHe, `${id} city_he`), // "" means outside the Hebrew top list
            lit(c.countryCode, "country_code"),
            "NULL",
            "NULL",
            String(popularity),
          ].join(", ") +
          ");",
      );
    });
  }
  return { rows, cityCount: cities.length };
}

export function generate(cities) {
  const { rows, cityCount } = buildRows(cities);
  const sorted = [...rows.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const header = [
    "-- GENERATED by scripts/gen-airports-sql.mjs from src/airports/cities.json - edit the JSON, not this file.",
    `-- ${cityCount} cities, ${rows.size} airports, one row per commercial airport (lat and lon unknown, left NULL).`,
    "-- The first airport of a city keeps the city popularity, the other airports of that city get 5 less.",
    "-- INSERT OR REPLACE makes re-running safe. Airports dropped from the dataset are not deleted here.",
    "",
  ];
  return header.concat(sorted.map((k) => rows.get(k))).join("\n") + "\n";
}

function main() {
  const sql = generate(JSON.parse(readFileSync(SRC, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      // missing file counts as out of date
    }
    if (current !== sql) {
      console.error("migrations/0002_seed_airports.sql is out of date: run node scripts/gen-airports-sql.mjs");
      process.exit(1);
    }
    console.log("migrations/0002_seed_airports.sql is up to date");
    return;
  }
  writeFileSync(OUT, sql);
  console.log(`wrote ${OUT} (${sql.split("\n").length - 1} lines)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
