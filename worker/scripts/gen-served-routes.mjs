#!/usr/bin/env node
/**
 * Builds src/airports/served.json: which airports had a DIRECT scheduled flight to or from Ben Gurion (TLV) in a
 * snapshot of the Israel Airports Authority flight board, and which bundled airports have no scheduled passenger
 * service at all. The Worker uses it only to ORDER and prune the airport pairs of a search (pipeline.airportPairs),
 * so the Travelpayouts request budget goes to pairs that can actually have fares. See docs/FLIGHT_API_RESEARCH.md §16.
 *
 *   node scripts/gen-served-routes.mjs <flydata.json> <ourairports-airports.csv>
 *
 * Inputs (both free, public, no key; download them once, they are NOT committed):
 *   flydata.json   https://data.gov.il/api/3/action/datastore_search?resource_id=e83f763b-b7d7-479e-b172-ae981ddc6de5&limit=5000
 *                  (IAA "מאגר טיסות", licence "Other (Open)", refreshed every 15 minutes, covers about 4-5 days of TLV traffic)
 *   airports.csv   https://davidmegginson.github.io/ourairports-data/airports.csv (OurAirports, public domain)
 *
 * Output is a pure function of the inputs: sorted lists, no wall-clock timestamp (the flight-board window is recorded).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CITIES = join(ROOT, "src", "airports", "cities.json");
const OUT = join(ROOT, "src", "airports", "served.json");
const IATA = /^[A-Z]{3}$/;

const [flydataPath, ourairportsPath] = process.argv.slice(2);
if (!flydataPath || !ourairportsPath) {
  console.error("usage: node scripts/gen-served-routes.mjs <flydata.json> <ourairports-airports.csv>");
  process.exit(2);
}

// --- IAA flight board -> airports with a direct TLV flight in the window ---------------------------------------
const board = JSON.parse(readFileSync(flydataPath, "utf8"));
const records = board?.result?.records;
if (!Array.isArray(records) || records.length < 100) throw new Error("flydata: expected result.records with at least 100 flights");
const direct = new Set();
let first = null;
let last = null;
for (const r of records) {
  const code = typeof r.CHLOC1 === "string" ? r.CHLOC1.trim().toUpperCase() : "";
  if (IATA.test(code) && code !== "TLV") direct.add(code);
  const when = typeof r.CHSTOL === "string" ? r.CHSTOL.slice(0, 10) : null;
  if (when && /^\d{4}-\d{2}-\d{2}$/.test(when)) {
    if (!first || when < first) first = when;
    if (!last || when > last) last = when;
  }
}
if (direct.size < 30) throw new Error(`flydata: only ${direct.size} destinations, refusing to write a thin table`);

// --- OurAirports -> bundled airports with no scheduled service -------------------------------------------------
/** Minimal RFC 4180 line splitter (quoted fields may contain commas; OurAirports has no embedded newlines in these columns). */
function splitCsvLine(line) {
  const out = [];
  let cur = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { out.push(cur); cur = ""; }
    else cur += c;
  }
  out.push(cur);
  return out;
}
const lines = readFileSync(ourairportsPath, "utf8").split(/\r?\n/).filter((l) => l !== "");
const header = splitCsvLine(lines[0]);
const iIata = header.indexOf("iata_code");
const iSched = header.indexOf("scheduled_service");
if (iIata < 0 || iSched < 0) throw new Error("airports.csv: iata_code / scheduled_service columns not found");
const scheduled = new Map(); // IATA -> true when ANY OurAirports row with that code has scheduled service
for (const line of lines.slice(1)) {
  const f = splitCsvLine(line);
  const code = (f[iIata] ?? "").trim().toUpperCase();
  if (!IATA.test(code)) continue;
  scheduled.set(code, scheduled.get(code) === true || f[iSched] === "yes");
}
const bundled = JSON.parse(readFileSync(CITIES, "utf8")).flatMap((c) => c.airports.map((a) => a.iata));
// Only airports OurAirports positively marks "no": an airport missing from OurAirports is unknown, never pruned.
const noScheduledService = [...new Set(bundled)].filter((a) => scheduled.get(a) === false).sort();

const out = {
  _about:
    "Generated by scripts/gen-served-routes.mjs. directFrom.TLV = airports seen with a direct flight to/from TLV on the IAA flight board (data.gov.il flydata) in `window`; a missing airport may still be served (seasonal, weekly) and connecting fares exist for any pair, so this only ORDERS searches. noScheduledService = bundled airports OurAirports marks scheduled_service=no.",
  window: { from: first, to: last, flights: records.length },
  directFrom: { TLV: [...direct].sort() },
  noScheduledService,
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${OUT}: ${direct.size} TLV destinations (${first}..${last}), no scheduled service: ${noScheduledService.join(", ") || "none"}`);
