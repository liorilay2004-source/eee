#!/usr/bin/env node
/**
 * Builds src/holidays.json: Israeli (Jewish and modern) holidays for today .. today + 24 months, from the free Hebcal
 * Jewish calendar REST API. The Worker reads the bundled file only (holidays.ts), so it makes ZERO runtime calls for
 * holidays. See docs/FLIGHT_API_RESEARCH.md §17.
 *
 *   node scripts/gen-holidays.mjs [YYYY-MM-DD]        (start date, default: today in UTC)
 *
 * On Node 22 behind an HTTPS proxy, run it with NODE_USE_ENV_PROXY=1 so fetch() uses HTTPS_PROXY.
 *
 * Source: https://www.hebcal.com/hebcal (docs: https://www.hebcal.com/home/195/jewish-calendar-rest-api).
 * Licence: content generated by the Hebcal.com web APIs is CC BY 4.0; credit "Hebcal.com, CC BY 4.0" (the API
 * responses carry it in the Worker as meta.holidaysAttribution, and the web legal page credits it). No key, no
 * registration; Hebcal answers 429 above 90 requests per 10 seconds. This script makes AT MOST 3 requests, one after
 * the other, one fetch each (no retries): a failed call stops the script and nothing is written.
 *
 * Parameters: i=on (Israel schedule: one-day chagim), lg=he (Hebrew titles), maj/min/mod=on (major, minor and modern
 * holidays), cfg=json, geo=none (no candle-lighting times), start/end (a Gregorian range per call).
 * Output: only items of category "holiday", sorted by date then title; niqqud is stripped from titles for display.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "holidays.json");
const API = "https://www.hebcal.com/hebcal";
const MONTHS = 24;
const CALLS = 3; // 24 months in 3 ranges of 8 months: the task's hard cap, and short ranges for the API
const ISO = /^\d{4}-\d{2}-\d{2}$/;
const DAY_MS = 86_400_000;

const arg = process.argv[2];
if (arg !== undefined && !ISO.test(arg)) {
  console.error("usage: node scripts/gen-holidays.mjs [YYYY-MM-DD]");
  process.exit(2);
}
const start = arg ?? new Date().toISOString().slice(0, 10);

/** "YYYY-MM-DD" plus n calendar months (the day is clamped to the month's end). */
function addMonths(iso, n) {
  const [y, m, d] = iso.split("-").map(Number);
  const idx = y * 12 + (m - 1) + n;
  const year = Math.floor(idx / 12);
  const month = (idx % 12) + 1;
  const last = new Date(Date.UTC(year, month, 0)).getUTCDate();
  return `${String(year).padStart(4, "0")}-${String(month).padStart(2, "0")}-${String(Math.min(d, last)).padStart(2, "0")}`;
}
const addDays = (iso, n) => new Date(Date.parse(`${iso}T00:00:00Z`) + n * DAY_MS).toISOString().slice(0, 10);

const end = addMonths(start, MONTHS);
const ranges = [];
for (let i = 0; i < CALLS; i++) {
  const from = addMonths(start, (MONTHS / CALLS) * i);
  const to = i === CALLS - 1 ? end : addDays(addMonths(start, (MONTHS / CALLS) * (i + 1)), -1);
  ranges.push([from, to]);
}

/** Hebrew points and cantillation (U+0591..U+05C7 except maqaf U+05BE and sof pasuq U+05C3). */
const stripNiqqud = (s) => s.replace(/[֑-ֽֿׁׂׄ-ׇ]/g, "").normalize("NFC");

const holidays = new Map();
for (const [from, to] of ranges) {
  const url = new URL(API);
  for (const [k, v] of Object.entries({ v: "1", cfg: "json", i: "on", lg: "he", maj: "on", min: "on", mod: "on", nx: "off", ss: "off", mf: "off", c: "off", geo: "none", start: from, end: to })) {
    url.searchParams.set(k, v);
  }
  const res = await fetch(url, { headers: { "User-Agent": "travel-price-engine gen-holidays (build-time, 3 requests per run)", Accept: "application/json" } });
  if (!res.ok) throw new Error(`hebcal ${from}..${to}: HTTP ${res.status}`);
  const body = await res.json();
  if (!Array.isArray(body?.items)) throw new Error(`hebcal ${from}..${to}: no items array`);
  for (const it of body.items) {
    if (it?.category !== "holiday") continue;
    const date = typeof it.date === "string" ? it.date.slice(0, 10) : "";
    const raw = typeof it.hebrew === "string" && it.hebrew.trim() !== "" ? it.hebrew : it.title;
    if (!ISO.test(date) || typeof raw !== "string" || raw.trim() === "") continue;
    const titleHe = stripNiqqud(raw.trim());
    const category = typeof it.subcat === "string" && it.subcat !== "" ? it.subcat : "holiday";
    holidays.set(`${date}|${titleHe}`, { date, titleHe, yomtov: it.yomtov === true, category });
  }
}

const list = [...holidays.values()].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : a.titleHe < b.titleHe ? -1 : a.titleHe > b.titleHe ? 1 : 0));
if (list.length < 40) throw new Error(`hebcal: only ${list.length} holidays for ${MONTHS} months, refusing to write a thin table`);
if (!list.some((h) => h.yomtov)) throw new Error("hebcal: no yom tov in the range, refusing to write");

const out = {
  _about: {
    source: "Hebcal.com Jewish calendar REST API (https://www.hebcal.com/hebcal), Israel schedule (i=on), Hebrew titles (lg=he)",
    licence: "CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); content generated by the Hebcal.com web APIs",
    attribution: "Hebcal.com, CC BY 4.0",
    changes: "Only category 'holiday' kept; niqqud stripped from titles; category = Hebcal subcat (major, minor, modern, fast, shabbat).",
    regenerate: "node scripts/gen-holidays.mjs [YYYY-MM-DD]",
  },
  range: { start, end },
  holidays: list,
};
writeFileSync(OUT, `${JSON.stringify(out, null, 1)}\n`);
console.log(`wrote ${OUT}: ${list.length} holidays, ${start} .. ${end}, ${ranges.length} requests`);
