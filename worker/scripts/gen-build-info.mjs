#!/usr/bin/env node
/**
 * Writes build/build-info.js (git-ignored) for GET /api/health: the commit and the time of this build.
 * Run by wrangler itself: wrangler.toml `[build] command` runs before every `npx wrangler deploy` / `wrangler dev`,
 * and `[alias]` points the module "eee-build-info" at the file written here. No extra step for the owner.
 * Never fails the deploy: without git (or outside a checkout) the commit is "unknown".
 * A local deploy from a checkout with uncommitted changes under worker/ gets "-dirty" appended, so health never claims
 * a clean commit that is not what actually runs (changes elsewhere in the repo, e.g. web/, do not affect this bundle).
 * The Workers runtime never sees this script (node: imports are fine here, not in src/).
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const workerDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(workerDir, "build", "build-info.js");

function commit() {
  // Cloudflare Workers Builds exposes the commit; a local deploy asks git.
  const ci = (process.env.WORKERS_CI_COMMIT_SHA ?? "").trim();
  if (/^[0-9a-f]{7,40}$/i.test(ci)) return ci.slice(0, 12).toLowerCase();
  const git = (args) =>
    execFileSync("git", ["-C", workerDir, ...args], { stdio: ["ignore", "pipe", "ignore"], timeout: 5000 }).toString().trim();
  let sha;
  try {
    sha = git(["rev-parse", "--short=12", "HEAD"]);
  } catch {
    return "unknown";
  }
  if (!/^[0-9a-f]{7,40}$/.test(sha)) return "unknown";
  try {
    // Only worker/ matters (build/ is git-ignored, so this file never marks itself dirty).
    if (git(["status", "--porcelain", "--", "."]) !== "") sha += "-dirty";
  } catch {
    // status unreadable: report the commit as is rather than fail the deploy
  }
  return sha;
}

const sha = commit();
const time = new Date().toISOString();
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/gen-build-info.mjs at deploy time. Do not edit, do not commit.\n` +
    `export const BUILD_SHA = ${JSON.stringify(sha)};\nexport const BUILD_TIME = ${JSON.stringify(time)};\n`,
);
console.log(`build-info: ${sha} ${time}`);
